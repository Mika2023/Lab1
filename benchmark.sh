#!/bin/bash

# Настройки
EXEC="./task2"
INPUT="big_input.txt"
OUTPUT="output.csv"
TEND="31536000"
DT="86400"
THREADS=(1 2 4 6 8)
RUNS=5

# Проверка, существует ли скомпилированная программа и файл с данными
if [ ! -f "$EXEC" ]; then
    echo "Ошибка: Файл $EXEC не найден! Скомпилируй программу."
    exit 1
fi

if [ ! -f "$INPUT" ]; then
    echo "Ошибка: Файл $INPUT не найден! Сгенерируй данные."
    exit 1
fi

echo "Начинаем тестирование ($RUNS запусков для каждого числа потоков)..."
echo "--------------------------------------------------------------------------------"
printf "%-10s | %-15s | %-15s | %-15s\n" "Потоки" "Среднее время (с)" "Ускорение (S)" "Эффективность (E)"
echo "--------------------------------------------------------------------------------"

time_1=0 # Переменная для хранения времени работы 1 потока

for t in "${THREADS[@]}"; do
    total_time=0
    
    # Запускаем программу RUNS раз
    for ((i=1; i<=RUNS; i++)); do
        # Запускаем программу, ищем строку с временем, вырезаем число и меняем запятую на точку (если русская локаль)
        time_val=$($EXEC $t $TEND $DT $INPUT $OUTPUT | grep "Затраченное время выполнения: " | awk '{print $4}' | sed 's/,/./')
        
        # Складываем время (используем awk для математики с плавающей точкой)
        total_time=$(awk "BEGIN {print $total_time + $time_val}")
    done
    
    # Вычисляем среднее время
    avg_time=$(awk "BEGIN {printf \"%.6f\", $total_time / $RUNS}")
    
    # Если это 1 поток, запоминаем его время как базовое
    if [ "$t" -eq 1 ]; then
        time_1=$avg_time
        speedup=1.000000
        efficiency=1.000000
    else
        # Вычисляем Ускорение = T1 / Tn
        speedup=$(awk "BEGIN {printf \"%.6f\", $time_1 / $avg_time}")
        # Вычисляем Эффективность = S / n
        efficiency=$(awk "BEGIN {printf \"%.6f\", $speedup / $t}")
    fi
    
    # Выводим строку таблицы
    printf "%-10s | %-15s | %-15s | %-15s\n" "$t" "$avg_time" "$speedup" "$efficiency"
done

echo "--------------------------------------------------------------------------------"
echo "Тестирование завершено!"